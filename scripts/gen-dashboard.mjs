// Regenerates src/Dashboard.tsx from the dashboard canvas template (code only; strips all embedded data).
// usage: node scripts/gen-dashboard.mjs /workspace/metrics/canvas_template.tsx
import fs from "fs";
const src = process.argv[2] || "/workspace/metrics/canvas_template.tsx";
let t = fs.readFileSync(src, "utf8");
const lines = t.split("\n");
lines[0] = lines[0].replace('from "grok/canvas"', 'from "./kit"');
t = lines.join("\n");
const rep = (re, s) => { if (!re.test(t)) throw new Error("pattern not found: " + re); t = t.replace(re, s); };
rep(/const D: any = __DATA__;\nconst ISA: any = D\.isa;\nconst AT: any = D\.attr;/,
  "let D: any = null;\nlet ISA: any = null;\nlet AT: any = null;\nlet PNL: any = null;\nexport function setData(d: any) { D = d; ISA = d.isa; AT = d.attr; PNL = d.pnl; }");
rep(/\nconst PNL: any = \{.*\};\n/, "\n");
// Ask (Sunburst-style coach) tab: site-only, injected here so the canvas template stays unchanged
rep(/\{ value: "recon", label: "Reconciliation" \}\];/, '{ value: "recon", label: "Reconciliation" }, { value: "ask", label: "Ask" }];');
rep(/attr: \["Lead attribution"\], pnl:/, 'ask: [], attr: ["Lead attribution"], pnl:');
rep(/return <Page title=\{el\.props\.title\} width=\{el\.props\.width\} summary=\{el\.props\.summary\}>\{kids\}<\/Page>;/,
  'const body = tab === "ask" ? [...kids.filter((c: any) => !(c.props && c.props.heading)), <Ask key="ask" data={D.coach} />] : kids;\n    return <Page title={el.props.title} width={el.props.width} summary={el.props.summary}>{body}</Page>;');
t = t.replace(/^(import .*\n)/, '$1import Ask from "./Ask";\n');
rep(/export default function App\(\)/, "export default function Dashboard()");
if (/__DATA__|"rows":\[\["Total for Income"/.test(t)) throw new Error("data left in output");
fs.writeFileSync(new URL("../src/Dashboard.tsx", import.meta.url), "// GENERATED by scripts/gen-dashboard.mjs from the dashboard template. Contains no data.\n// @ts-nocheck\n" + t);
console.log("wrote src/Dashboard.tsx");
